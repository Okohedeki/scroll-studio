"""Layout snapshot of an example: where every section's words sit and when they show, without building anything.

The 1.5 release gate (docs/design/1.5-make-it-yours.md) is that every example compiles to the same placement before and
after the layout model is replaced. A build renders (GPU, ComfyUI, Blender), so this renders only the page: it loads the
spec (its validators run, so placement they fill is covered), gives every scene a stand-in config in place of the
builder's, renders the real `site.html.j2` through the compiler's own Jinja environment (the blocks and scenes of the
active style included) and reads the placement facts out of the markup with the stdlib HTML parser.

What is kept is only what places things: classes, data-* and inline styles of the layout skeleton (stage, captions,
steps, cards, panels, cut wrappers, block sections, journey stops), the first words of each caption's kicker and title,
the cuts the page carries and the `sdata` the compiler embeds. Hashes, asset paths and anything a render decides are
left out; a section whose placement a builder decides at render time carries a `note` saying so.
"""
from __future__ import annotations

import json
import re
from html.parser import HTMLParser
from pathlib import Path
from typing import Any, Optional

from ..project import Project
from ..spec import Site, is_scene

SDATA_FIELDS = {"hud", "steps", "layout", "length"}      # what the compiler embeds per scene (`.ss-section`)
TEXT_CHARS = 40                                          # how much of a kicker / title is kept

# ---- which elements of the markup are placement (everything else is content and left out)
_LAYOUT = re.compile(
    r"^(ss-(scene|block|band|panel|backdrop|cutw|cutpin|cutgap|track|stage|captions|caption|steps|step|card|pin|split-grid|hud|"
    r"cue|shade|intro|intro2|hero|product|features|stats|timeline|orbit|faq|strip|cta|gallery|has-world)(--[\w-]+|__[\w-]+)?"
    r"|ss-(side|type|surface|shade|pose)[-_][\w-]+"
    r"|jy-(scene|stops|stop|blk|body|rail)(--[\w-]+|__[\w-]+)?|jy-(side|surface|form)-[\w-]+)$")
_PLACING_DATA = {"data-from", "data-to", "data-world", "data-stop", "data-scene", "data-cut-in", "data-cut-out"}
_VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
_KICKERS = {"ss-eyebrow", "ss-num", "ss-kicker", "jy-kicker"}
_TEXT_HOLDERS = re.compile(r"^(ss-caption|ss-step|ss-block|ss-scene|jy-stop|jy-blk)(\b|$)")


class Node:
    __slots__ = ("tag", "attrs", "children", "content")

    def __init__(self, tag: str, attrs: dict[str, str]):
        self.tag, self.attrs, self.children, self.content = tag, attrs, [], []    # content: text runs and children, in order

    @property
    def classes(self) -> list[str]:
        return (self.attrs.get("class") or "").split()

    def plain(self) -> str:
        """Every text run under the node, whitespace collapsed."""
        return re.sub(r"\s+", " ", "".join(c if isinstance(c, str) else c.plain() for c in self.content)).strip()


class _Tree(HTMLParser):
    """A small DOM: the markup is generated by our own templates, so it is well formed; a stray end tag is ignored."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("#root", {})
        self.stack = [self.root]
        self.skip = 0                                    # inside <script> / <style>: their text is not markup

    def handle_starttag(self, tag, attrs):
        node = Node(tag, {k: (v if v is not None else "") for k, v in attrs})
        self.stack[-1].children.append(node)
        self.stack[-1].content.append(node)
        if tag in _VOID:
            return
        self.stack.append(node)
        if tag in ("script", "style"):
            self.skip += 1

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in _VOID and self.stack[-1].tag == tag:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                if tag in ("script", "style"):
                    self.skip -= 1
                del self.stack[i:]
                return

    def handle_data(self, data):
        if not self.skip:
            self.stack[-1].content.append(data)


def parse(html: str) -> Node:
    t = _Tree()
    t.feed(html)
    t.close()
    return t.root


def _find(node: Node, tag: str) -> Optional[Node]:
    for c in node.children:
        if c.tag == tag:
            return c
        hit = _find(c, tag)
        if hit is not None:
            return hit
    return None


def _style(value: str) -> dict[str, str]:
    """Inline style as {property: value}; a background image is a render's asset, not placement."""
    out = {}
    for decl in value.split(";"):
        if ":" in decl:
            k, v = decl.split(":", 1)
            if k.strip() != "background-image":
                out[k.strip()] = re.sub(r"\s+", " ", v.strip())
    return out


def _is_placement(n: Node) -> bool:
    """A layout class, a placing data attribute, or (so a style's own markup is covered too) any BEM modifier such as
    `x-product--right` on something that is not a link."""
    return (any(_LAYOUT.match(c) for c in n.classes) or bool(_PLACING_DATA & set(n.attrs))
            or (n.tag != "a" and any("--" in c for c in n.classes)))


def _first(node: Node, match) -> Optional[Node]:
    for c in node.children:
        if match(c):
            return c
        hit = _first(c, match)
        if hit is not None:
            return hit
    return None


def _words(node: Node) -> dict[str, str]:
    """The first words of the kicker and of the title (h1/h2): enough to tell captions apart in a diff."""
    out = {}
    kick = _first(node, lambda c: bool(_KICKERS & set(c.classes)))
    title = _first(node, lambda c: c.tag in ("h1", "h2"))
    if kick is not None and kick.plain():
        out["kicker"] = kick.plain()[:TEXT_CHARS]
    if title is not None:
        out["title"] = title.plain()[:TEXT_CHARS]
        out["title_tag"] = title.tag
    return out


def _record(n: Node, force: bool = False) -> list[dict]:
    """The placement elements at and under `n`, nested by containment: an element that is not placement is skipped and
    its placement children are lifted into the nearest placement ancestor."""
    kids = [r for c in n.children for r in _record(c)]
    if not (force or _is_placement(n)):
        return kids
    rec: dict[str, Any] = {"tag": n.tag, "class": n.classes}
    if "id" in n.attrs:
        rec["id"] = n.attrs["id"]
    data = {k: v for k, v in n.attrs.items() if k.startswith("data-")}
    if data:
        rec["data"] = data
    style = _style(n.attrs.get("style", ""))
    if style:
        rec["style"] = style
    if any(_TEXT_HOLDERS.match(c) for c in n.classes):
        words = _words(n)
        if words:
            rec["text"] = words
    if kids:
        rec["children"] = kids
    return [rec]


# ---------------------------------------------------------------- the stand-in for a build

def _media(s) -> dict:
    """The media a block shows, as the compiler's `block_media` keys them, but only whether there is one: a picture the
    spec names is a picture the build writes, and its path is not placement."""
    def has(v):
        return "standin" if v else None
    x: dict[str, Any] = {"backdrop": has(getattr(s, "backdrop", None))}
    if s.type == "hero":
        x.update(img=has(s.image), video=has(s.video), screen=has(s.device and s.device.image), clip=has(s.device and s.device.video))
    elif s.type == "product":
        x.update(img=has(s.image), screen=has(s.device and s.device.image), clip=has(s.device and s.device.video),
                 behind=has(s.behind and s.behind.image), behind_clip=has(s.behind and s.behind.video))
    elif s.type == "strip":
        x["imgs"] = ["standin" for _ in s.items]
    return x


def _sdata(sec) -> Optional[dict]:
    return sec.model_dump(mode="json", include=SDATA_FIELDS) if is_scene(sec) else None


def _entries(site: Site, cuts_cfg: list[dict]) -> list[dict]:
    """The compiler's section entries with a stand-in config: a poster and nothing else, which is all the scene templates
    read (the journey's measured `cfg.journey` is absent, so its stops use the side and surface the spec gives)."""
    entries = []
    for i, sec in enumerate(site.sections):
        e = {"s": sec, "scene": is_scene(sec), "config": {"poster": "standin"} if is_scene(sec) else None,
             "sdata": _sdata(sec), "first": i == 0, "cut_in": None, "cut_out": None}
        if sec.type == "gallery":
            e["s"] = sec.model_copy(update={"items": [it.model_copy(update={"image": "standin" if it.image else None,
                                                                            "video": "standin" if it.video else None})
                                                      for it in sec.items]})
        e.update(_media(sec))
        if getattr(sec, "journey", None) is not None:
            e["jx"] = {st.id: [_media(b) for b in st.blocks] for st in sec.journey.stops}
        if sec.type == "cta" and getattr(sec, "background", None):
            e["bg"] = "standin"
        entries.append(e)
    for c in cuts_cfg:
        entries[c["a"]]["cut_out"], entries[c["b"]]["cut_in"] = c["n"], c["n"]
    return entries


def _page(site: Site, entries: list[dict], theme: dict, cuts_cfg: list[dict]) -> str:
    """site.html.j2 rendered the way `build_site` calls it, minus everything that is not about the sections."""
    from . import themes
    from .compiler import _env
    sdir = themes.style_dir(theme["style"]) if theme["style"] else None
    env = _env(sdir, theme.get("skin"))
    env.globals["art"] = None
    return env.get_template("site.html.j2").render(
        site=site, sections=entries, theme=theme, css_vars="", logo=None, font_css="", font_links=[], nav_links=[],
        page_links=[], credits=[], concept=None, product=site.product,
        configs={e["s"].id: e["config"] for e in entries if e["scene"]},
        style_css="", style_blocks=bool(sdir and (sdir / "blocks.html.j2").exists()),
        style_chrome=bool(sdir and (sdir / "chrome.html.j2").exists()),
        style_scenes=bool(sdir and (sdir / "scenes.html.j2").exists()),
        runtime="runtime/", looks=None, icon="", trailer=None, cuts=cuts_cfg)


def _cuts(site: Site, theme: dict) -> list[dict]:
    from .. import cuts as cuts_mod
    from . import themes
    cfg = themes.styles().get(theme["style"], {}) if theme["style"] else {}
    blocked = f"the {theme['style']} style plays its own hand-over between sections" if cfg.get("cuts") is False else None
    return cuts_mod.plan(site, lambda m: None, None, blocked)


def _notes(sec) -> list[str]:
    """What a builder decides at render time for this section, so the snapshot cannot show it (never skipped silently)."""
    notes = []
    steps = getattr(sec, "steps", None) or []
    unset = [st for st in steps if st.at is None]
    if sec.type == "inside" and steps:
        notes.append("the scene builder schedules the steps' windows (`at`) along the route and sets the scroll length "
                     "(engine/inside.py schedule_steps): shown as the spec leaves them")
    elif sec.type == "light" and sec.layout == "overlay" and unset:
        notes.append("the scene builder gives steps without `at` a window around the light's hold (engine/scenes/light.py)")
    elif sec.type == "film" and any((st.state or {}).get("beat") is not None for st in unset):
        notes.append("steps pinned to a beat (`state.beat`) get their window from the beat's span in the joined film "
                     "(engine/scenes/film.py pin_steps), known only once the beats are rendered")
    elif sec.type == "code" and any((st.state or {}).get("file") is not None for st in unset):
        notes.append("steps pinned to a file (`state.file`) get their window from the file's span in the scene "
                     "(engine/scenes/code.py), known only once the scene is built")
    j = getattr(sec, "journey", None)
    if j is not None and any(st.side == "auto" or st.surface == "auto" for st in j.stops):
        notes.append("a journey stop with side/surface `auto` takes them from its rendered picture (engine/journey.py "
                     "measurement); the snapshot shows the fallback: left, dark")
    return notes


def page_html(site: Site) -> str:
    """The whole page of a loaded spec, rendered with stand-ins for every render (the conformance tests draw every
    style with every block type this way)."""
    from . import themes
    theme = themes.resolve(site.theme)
    cuts_cfg = _cuts(site, theme)
    return _page(site, _entries(site, cuts_cfg), theme, cuts_cfg)


# ---------------------------------------------------------------- the snapshot

def layout_snapshot(site_yaml_path) -> dict:
    """The placement facts of one example (see the module docstring), deterministic and JSON-serialisable."""
    from . import themes
    path = Path(site_yaml_path)
    site = Project(path.parent).load()
    theme = themes.resolve(site.theme)
    cuts_cfg = _cuts(site, theme)
    entries = _entries(site, cuts_cfg)
    tree = parse(_page(site, entries, theme, cuts_cfg))
    html = _find(tree, "html")
    main = _find(tree, "main")
    roots = [c for c in main.children if c.tag != "script"]
    if len(roots) != len(site.sections):
        raise ValueError(f"{path}: {len(site.sections)} sections rendered {len(roots)} top-level elements in <main>; "
                         f"the snapshot reads one per section")
    sections = []
    for sec, root in zip(site.sections, roots):
        out: dict[str, Any] = {"id": sec.id, "type": sec.type, "markup": _record(root, force=True)}
        if is_scene(sec):
            out["sdata"] = _sdata(sec)
        notes = _notes(sec)
        if notes:
            out["note"] = "; ".join(notes)
        sections.append(out)
    snap: dict[str, Any] = {
        "example": path.parent.name,
        "root": {"class": html.classes, **({"data-style": html.attrs["data-style"]} if "data-style" in html.attrs else {})},
        "cuts": cuts_cfg,
        "sections": sections,
    }
    notes = []
    covered = [s["id"] for s in sections if "note" in s]
    if covered:
        notes.append("not fully covered without a render: " + ", ".join(covered) + " (see each section's note)")
    if any(c["type"] == "match" for c in cuts_cfg):
        notes.append("match-cut anchors (where the shapes sit in the rendered frames) are found from renders and are not covered")
    if theme["style"] and (themes.style_dir(theme["style"]) / "blocks.html.j2").exists():
        notes.append(f"the {theme['style']} style sets its own block markup: covered by its section classes and modifier "
                     f"classes, not by every element")
    if notes:
        snap["note"] = "; ".join(notes)
    return json.loads(json.dumps(snap))       # plain JSON types only (tuples -> lists), as a snapshot file reads back


# ---------------------------------------------------------------- comparing

def _flat(markup: list[dict], prefix: str = "") -> dict[str, dict]:
    """{path: the element's own facts} for a recorded tree; the path is the tags and first classes down from the section,
    numbered among siblings that look the same, so a diff can say which element changed."""
    seen: dict[str, int] = {}
    out: dict[str, dict] = {}
    for rec in markup:
        label = rec["tag"] + ("." + rec["class"][0] if rec["class"] else "")
        k = seen[label] = seen.get(label, -1) + 1
        path = f"{prefix}/{label}[{k}]"
        out[path] = {f: rec[f] for f in ("id", "class", "data", "style", "text") if f in rec}
        out.update(_flat(rec.get("children", []), path))
    return out


def diff_layout(old: dict, new: dict) -> list[str]:
    """Readable lines for every difference between two snapshots: section, element, field, old -> new."""
    lines: list[str] = []

    def cmp(where: str, a: Any, b: Any):
        """One line per leaf that differs (a dict or list is walked: `[s] sdata.steps[0].place: null -> "top-right"`)."""
        if a == b:
            return
        if isinstance(a, dict) and isinstance(b, dict):
            for k in list(a) + [k for k in b if k not in a]:
                cmp(f"{where}.{k}", a.get(k), b.get(k))
        elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
            for i, (x, y) in enumerate(zip(a, b)):
                cmp(f"{where}[{i}]", x, y)
        else:
            lines.append(f"{where}: {json.dumps(a, ensure_ascii=False)} -> {json.dumps(b, ensure_ascii=False)}")
    cmp("root classes", old.get("root"), new.get("root"))
    cmp("cuts", old.get("cuts"), new.get("cuts"))
    cmp("note", old.get("note"), new.get("note"))
    cmp("section order", [s["id"] for s in old.get("sections", [])], [s["id"] for s in new.get("sections", [])])
    olds = {s["id"]: s for s in old.get("sections", [])}
    news = {s["id"]: s for s in new.get("sections", [])}
    for sid in list(olds) + [i for i in news if i not in olds]:
        a, b = olds.get(sid), news.get(sid)
        if a is None or b is None:
            lines.append(f"[{sid}] section {'added' if a is None else 'removed'}")
            continue
        cmp(f"[{sid}] type", a["type"], b["type"])
        cmp(f"[{sid}] sdata", a.get("sdata"), b.get("sdata"))
        cmp(f"[{sid}] note", a.get("note"), b.get("note"))
        fa, fb = _flat(a["markup"]), _flat(b["markup"])
        for path in list(fa) + [p for p in fb if p not in fa]:
            if path not in fb:
                lines.append(f"[{sid}] {path}: element removed {json.dumps(fa[path], ensure_ascii=False)}")
            elif path not in fa:
                lines.append(f"[{sid}] {path}: element added {json.dumps(fb[path], ensure_ascii=False)}")
            else:
                cmp(f"[{sid}] {path}", fa[path], fb[path])
    return lines
