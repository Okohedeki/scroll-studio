# ---------------------------------------------------------------- shared text helpers

_CODE = re.compile(r"(`[^`\n]*`)")
_ATTR = re.compile(r"\{(?=[:#. ])")      # attr_list would read `{ #id }` or `{: .class }` as attributes
MAX_DEFAULT = 48           # longer defaults are cut: the full value is in the source


def prose(text: str) -> str:
    """Escape what would be read as Markdown or HTML in plain text, leaving `code spans` as written. Table cells
    also need their pipes escaped, and line breaks turned into spaces."""
    out = []
    for part in _CODE.split(" ".join(text.split())):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(part.replace("|", "\\|"))
        else:
            out.append(_ATTR.sub("&#123;", part.replace("\\", "\\\\").replace("<", "&lt;")
                                .replace("*", "\\*").replace("|", "\\|")))
    return "".join(out)


def block(text: str) -> str:
    """Docstring text as Markdown paragraphs: de-indented, soft-wrapped lines kept, HTML-ish characters escaped
    outside code. Fenced code in a docstring is kept verbatim."""
    text = inspect.cleandoc(text or "")
    out, fenced = [], False
    for line in text.splitlines():
        if line.strip().startswith("```"):
            fenced = not fenced
            out.append(line)
        elif fenced:
            out.append(line)
        else:
            out.append("".join(p if _CODE.fullmatch(p) else p.replace("<", "&lt;")
                               for p in _CODE.split(line)))
    return "\n".join(out)


_SENTENCE_END = re.compile(r"(?<!e\.g)(?<!i\.e)(?<!etc)[.!?](?=\s+[A-Z`(\"']|$)")


def first_sentence(text: str, limit: int = 170) -> str:
    """The first sentence of a docstring for an overview table, cut at a word when it runs on."""
    text = " ".join(inspect.cleandoc(text or "").split())
    m = _SENTENCE_END.search(text)
    out = text[:m.end()] if m else text
    if len(out) > limit:
        out = out[:limit].rsplit(" ", 1)[0].rstrip(",;:( ") + " …"
    return out


def code(value: Any) -> str:
    """A value as it would be written in YAML, in a code span, cut when long."""
    s = json.dumps(value, ensure_ascii=False)
    if len(s) > MAX_DEFAULT:
        s = s[:MAX_DEFAULT - 1].rstrip() + "…"
    return "`" + s.replace("`", "'") + "`"


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")
    return path


GENERATED = "<!-- Generated by `python -m engine.docsgen`. Do not edit: change the source and regenerate. -->\n"


# ---------------------------------------------------------------- JSON Schema, read for people

def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _non_null(s: dict) -> list[dict]:
    return [b for b in s.get("anyOf", []) if b.get("type") != "null"]


def refs_in(s: Any) -> Iterable[str]:
    """Every model a schema fragment points at."""
    if isinstance(s, dict):
        if "$ref" in s:
            yield ref_name(s["$ref"])
        for v in s.values():
            yield from refs_in(v)
    elif isinstance(s, list):
        for v in s:
            yield from refs_in(v)


def is_optional(s: dict) -> bool:
    return any(b.get("type") == "null" for b in s.get("anyOf", []))


def type_md(s: dict, link: Callable[[str], str]) -> str:
    """The type of a field in words, with models linked."""
    if "$ref" in s:
        return link(ref_name(s["$ref"]))
    if "const" in s:
        return code(s["const"])
    if "enum" in s:
        return "enum"
    if "anyOf" in s:
        parts = [type_md(b, link) for b in _non_null(s)]
        return " or ".join(dict.fromkeys(parts)) or "null"
    if "oneOf" in s:
        targets = [ref_name(b["$ref"]) for b in s["oneOf"] if "$ref" in b]
        if len(targets) > 4 and "discriminator" in s:
            kind = s["discriminator"]["propertyName"]
            return f"one of {len(targets)} models, chosen by `{kind}`: " + ", ".join(link(t) for t in targets)
        return " or ".join(type_md(b, link) for b in s["oneOf"])
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            items = [type_md(b, link) for b in s["prefixItems"]]
            if len(set(items)) == 1:
                return f"list of {len(items)} {items[0]}s" if items[0] in ("number", "integer", "string") else \
                    f"list of {len(items)} × {items[0]}"
            return "[" + ", ".join(items) + "]"
        return "list of " + type_md(s.get("items", {}), link)
    if t == "object":
        extra = s.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return "map of string to " + type_md(extra, link)
        return "map"
    if isinstance(t, str):
        return t
    return "any"


def enums_in(s: dict) -> list[list[Any]]:
    out = []
    if "enum" in s:
        out.append(s["enum"])
    for b in s.get("anyOf", []):
        out += enums_in(b)
    if isinstance(s.get("items"), dict):
        out += enums_in(s["items"])
    return out


def _range(lo: Any, hi: Any, lo_ex: Any, hi_ex: Any) -> str | None:
    if lo is not None and hi is not None:
        return f"{lo} to {hi}"
    if lo is not None:
        return f"at least {lo}"
    if hi is not None:
        return f"at most {hi}"
    if lo_ex is not None and hi_ex is not None:
        return f"above {lo_ex}, below {hi_ex}"
    if lo_ex is not None:
        return f"above {lo_ex}"
    if hi_ex is not None:
        return f"below {hi_ex}"
    return None


def constraints_in(s: dict) -> list[str]:
    out = []
    r = _range(s.get("minimum"), s.get("maximum"), s.get("exclusiveMinimum"), s.get("exclusiveMaximum"))
    if r:
        out.append(r)
    for key, noun in (("Items", "items"), ("Length", "characters")):
        lo, hi = s.get("min" + key), s.get("max" + key)
        if lo is not None and hi is not None:
            out.append(f"{lo} to {hi} {noun}" if lo != hi else f"exactly {lo} {noun}")
        elif lo is not None:
            out.append(f"at least {lo} {noun}")
        elif hi is not None:
            out.append(f"at most {hi} {noun}")
    if "pattern" in s:
        out.append(f"matches `{s['pattern']}`")
    if "multipleOf" in s:
        out.append(f"a multiple of {s['multipleOf']}")
    for b in s.get("anyOf", []):
        out += constraints_in(b)
    if isinstance(s.get("items"), dict):
        out += ["each: " + c for c in constraints_in(s["items"])]
    if "prefixItems" in s:
        lines = {tuple(constraints_in(b)) for b in s["prefixItems"]}
        if len(lines) == 1:
            out += ["each: " + c for c in next(iter(lines))]
    return list(dict.fromkeys(out))


# ---------------------------------------------------------------- the site.yaml reference

def _own_fields(cls: type[BaseModel], base: type[BaseModel] | None) -> list[str]:
    """Fields a model adds to (or changes from) its shared base."""
    if base is None or not issubclass(cls, base) or cls is base:
        return list(cls.model_fields)
    return [k for k, f in cls.model_fields.items() if k not in base.model_fields or repr(f) != repr(base.model_fields[k])]


class SpecDocs:
    """Groups every spec model into pages and renders them."""

    PAGES = {
        "site": ("Site and theme", "The whole file, and the settings that apply to the whole site."),
        "scenes": ("Scenes", "Sections with a scroll-driven visual. Each is chosen by `type`."),
        "blocks": ("Blocks", "Static content sections. Each is chosen by `type`."),
        "nested": ("Nested models", "The pieces the models above are built from."),
    }

    def __init__(self) -> None:
        self.schema = spec_mod.Site.model_json_schema()
        self.defs: dict[str, dict] = dict(self.schema["$defs"])
        self.scene_base = spec_mod.SceneBase.model_json_schema()
        self.block_base = spec_mod.BlockBase.model_json_schema()
        for extra in (self.scene_base, self.block_base):
            for k, v in extra.get("$defs", {}).items():
                self.defs.setdefault(k, v)
        self.classes: dict[str, type[BaseModel]] = {
            n: c for n, c in vars(spec_mod).items()
            if isinstance(c, type) and issubclass(c, BaseModel) and c.__module__ == spec_mod.__name__}
        sections = self.schema["properties"]["sections"]["items"]["oneOf"]
        order = [ref_name(b["$ref"]) for b in sections]
        scene_names = [n for n in order if issubclass(self.classes[n], spec_mod.SceneBase)]
        block_names = [n for n in order if issubclass(self.classes[n], spec_mod.BlockBase)]
        site_names = ["Site"] + [n for n in dict.fromkeys(refs_in(self.schema["properties"]))
                                 if n not in scene_names + block_names]
        placed = set(site_names + scene_names + block_names)
        nested = sorted(n for n in self.defs if n not in placed)
        self.groups = {"site": site_names, "scenes": scene_names, "blocks": block_names, "nested": nested}
        self.page_of = {n: p for p, names in self.groups.items() for n in names}
        self.page_of["SceneBase"] = "scenes"
        self.page_of["BlockBase"] = "blocks"
        self.used_in = self._used_in()

    # --- model schemas

    def model_schema(self, name: str) -> dict:
        if name == "Site":
            return {k: v for k, v in self.schema.items() if k != "$defs"} | {"description": spec_mod.__doc__ or ""}
        if name == "SceneBase":
            return self.scene_base
        if name == "BlockBase":
            return self.block_base
        return self.defs[name]

    def base_of(self, name: str) -> str | None:
        cls = self.classes[name]
        for b in (spec_mod.SceneBase, spec_mod.BlockBase):
            if issubclass(cls, b) and cls is not b:
                return b.__name__
        return None

    def fields_of(self, name: str) -> list[str]:
        """The field names this model's section lists: all of them, or only its own when it has a shared base."""
        sch = self.model_schema(name)["properties"]
        base = self.base_of(name)
        if base is None:
            return list(sch)
        return [k for k in _own_fields(self.classes[name], self.classes[base]) if k in sch]

    def _used_in(self) -> dict[str, list[tuple[str, str]]]:
        used: dict[str, list[tuple[str, str]]] = {}
        for name in list(self.defs) + ["Site", "SceneBase", "BlockBase"]:
            if name not in self.classes:
                continue
            props = self.model_schema(name).get("properties", {})
            for f in self.fields_of(name):
                for r in dict.fromkeys(refs_in(props[f])):
                    used.setdefault(r, []).append((name, f))
        return used

    # --- links

    @staticmethod
    def anchor(name: str) -> str:
        return name.lower()

    def link(self, name: str, from_page: str) -> str:
        page = self.page_of.get(name)
        if page is None:
            return f"`{name}`"
        target = f"#{self.anchor(name)}" if page == from_page else f"{page}.md#{self.anchor(name)}"
        return f"[{name}]({target})"

    def field_link(self, model: str, field: str, from_page: str) -> str:
        page = self.page_of[model]
        target = f"#{self.anchor(model)}-{field}" if page == from_page else f"{page}.md#{self.anchor(model)}-{field}"
        return f"[{model}.{field}]({target})"

    # --- rendering

    def default_text(self, model: str, field: str, s: dict) -> str:
        """The default as written in YAML. The JSON Schema leaves out defaults made by a factory (empty lists,
        sub-models), so those are read from the model itself."""
        if "default" in s:
            return code(s["default"])
        info = self.classes[model].model_fields.get(field) if model in self.classes else None
        if info is not None and info.default_factory is not None:
            value = info.default_factory()
            if isinstance(value, BaseModel):
                return "`{}` (its own defaults)"
            return code(value)
        return ""

    def field_row(self, model: str, field: str, s: dict, required: bool, page: str) -> str:
        link = lambda n: self.link(n, page)  # noqa: E731
        typ = type_md(s, link)
        if is_optional(s):
            typ += " (optional)" if "default" in s and s["default"] is None else ""
        default = "**required**" if required else self.default_text(model, field, s)
        notes = [prose(s["description"])] if s.get("description") else []
        for rule in s.get("x-deprecated", []):
            lead = "**Deprecated:**" if "value" not in rule else f"**Deprecated value** {code(rule['value'])}:"
            notes.append(f"{lead} {prose(spec_mod.deprecation_tail(rule))}")
        for allowed in enums_in(s):
            notes.append("Allowed values: " + ", ".join(code(v) for v in allowed) + ".")
        cons = constraints_in(s)
        if cons:
            notes.append("Constraints: " + "; ".join(cons) + ".")
        anchor = f'<a id="{self.anchor(model)}-{field}"></a>'
        return f"| {anchor}`{field}` | {typ} | {default} | {'<br>'.join(notes)} |"

    def model_section(self, name: str, page: str) -> str:
        sch = self.model_schema(name)
        cls = self.classes[name]
        lines = [f"## {name} {{ #{self.anchor(name)} }}", ""]
        const = sch.get("properties", {}).get("type", {}).get("const")
        if const is not None:
            lines += [f"A section with `type: {const}`.", ""]
        doc = ((spec_mod.__doc__ if name == "Site" else cls.__doc__) or "").strip()      # Site is described by the module
        if doc:
            lines += [block(doc), ""]
        base = self.base_of(name)
        if base:
            lines += [f"Also takes every field of {self.link(base, page)}.", ""]
        required = set(sch.get("required", []))
        fields = self.fields_of(name)
        if fields:
            lines += ["| Field | Type | Default | Description |", "| --- | --- | --- | --- |"]
            lines += [self.field_row(name, f, sch["properties"][f], f in required, page) for f in fields]
            lines.append("")
        else:
            lines += ["No fields of its own.", ""]
        uses = self.used_in.get(name, [])
        if uses:
            shown = ", ".join(self.field_link(m, f, page) for m, f in uses[:8])
            more = f" and {len(uses) - 8} more" if len(uses) > 8 else ""
            lines += [f"Used in: {shown}{more}.", ""]
        return "\n".join(lines)

    def page(self, key: str) -> str:
        title, intro = self.PAGES[key]
        lines = [GENERATED, f"# {title}", "", intro, ""]
        names = list(self.groups[key])
        if key == "site":
            lines += ["The top level of `site.yaml` is the `Site` model below; every other model here is a key under it "
                      "or under one of its keys.", ""]
        if key == "scenes":
            lines += ["Every scene also takes the fields of `SceneBase`, listed first. Where a scene's `type` is one of "
                      "these, its own fields follow.", ""]
            names = ["SceneBase"] + names
        if key == "blocks":
            names = ["BlockBase"] + names
        if key == "nested":
            lines += ["Alphabetical. Each says where it is used.", ""]
        lines += [self.model_section(n, key) for n in names]
        return "\n".join(lines)

    def index(self) -> str:
        total = sum(len(v) for v in self.groups.values())
        lines = [GENERATED, "# site.yaml reference", "",
                 f"Every model and field a `site.yaml` can hold, read from `engine/spec.py` ({total} models). "
                 "The Studio forms, `studio schema` and the MCP tool `spec_schema` come from the same source, "
                 "so this page is what the engine accepts today.", "",
                 "- Unknown keys are errors: every model rejects fields it does not define.",
                 "- *Default* is what the engine uses when you leave the field out; **required** fields have none.",
                 "- *Optional* fields have the default `null`: leaving them out means the feature is off.", "",
                 "## Pages", ""]
        for key, (title, intro) in self.PAGES.items():
            lines.append(f"- [{title}]({key}.md): {intro} ({len(self.groups[key])} models)")
        lines += ["", "## Scene and block types", "",
                  "The `type` of a section picks its model.", "",
                  "| `type` | Model | What it is |", "| --- | --- | --- |"]
        for key in ("scenes", "blocks"):
            for n in self.groups[key]:
                const = self.model_schema(n)["properties"]["type"].get("const", "")
                lines.append(f"| `{const}` | {self.link(n, 'index')} | {prose(first_sentence(self.classes[n].__doc__ or ''))} |")
        lines += ["", "## Every model", "", " · ".join(self.link(n, "index") for n in sorted(self.page_of)), ""]
        return "\n".join(lines)

    def render(self) -> dict[str, str]:
        out = {"index.md": self.index()}
        out |= {f"{k}.md": self.page(k) for k in self.PAGES}
        return out


# ---------------------------------------------------------------- the CLI reference
# typer 0.27 carries its own copy of click, so the command objects are read by duck typing, never isinstance.

def _click_command() -> Any:
    import typer.main
    from .cli import app
    return typer.main.get_command(app)


def _is_group(cmd: Any) -> bool:
    return hasattr(cmd, "commands")


def _is_argument(param: Any) -> bool:
    return getattr(param, "param_type_name", "") == "argument"


def _default_text(param: Any) -> str:
    if param.required:
        return "**required**"
    default = param.default
    if default is None or type(default).__name__ in ("Sentinel", "UnsetType") or default in ((), ""):
        return ""
    if callable(default):
        return "computed"
    if getattr(param, "is_flag", False) and default is False:
        return "off"
    return code(default if isinstance(default, (bool, int, float, str, list)) else str(default))


def _type_text(param: Any) -> str:
    t = param.type
    if type(t).__name__ == "Choice":
        base = "choice: " + ", ".join(f"`{c}`" for c in t.choices)
    elif getattr(param, "is_flag", False):
        base = "flag"
    else:
        base = {"text": "text", "string": "text", "str": "text", "integer": "integer", "int": "integer",
                "float": "number", "boolean": "yes/no", "bool": "yes/no", "path": "path",
                "filename": "path"}.get(t.name.lower(), t.name.lower())
    if getattr(param, "multiple", False):
        base += ", repeatable"
    return base


def _option_names(opt: Any) -> str:
    names = " / ".join(f"`{o}`" for o in opt.opts)
    if opt.secondary_opts:
        names += " / " + " / ".join(f"`{o}`" for o in opt.secondary_opts)
    return names


def _usage(full: str, cmd: Any) -> str:
    parts = [full, "[OPTIONS]"] if any(not _is_argument(p) and p.name != "help" for p in cmd.params) else [full]
    for p in cmd.params:
        if _is_argument(p):
            name = p.human_readable_name.upper() + ("..." if p.nargs == -1 else "")
            parts.append(name if p.required else f"[{name}]")
    return " ".join(parts)


def _commands(group: Any, prefix: str) -> Iterable[tuple[str, Any]]:
    for name, cmd in group.commands.items():
        if getattr(cmd, "hidden", False):
            continue
        if _is_group(cmd):
            yield from _commands(cmd, f"{prefix} {name}")
        else:
            yield f"{prefix} {name}", cmd


def _anchor(full: str) -> str:
    return full.replace(" ", "-")


def _param_table(kind: str, params: list[Any]) -> list[str]:
    lines = [f"| {kind} | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for p in params:
        label = f"`{p.human_readable_name}`" if _is_argument(p) else _option_names(p)
        lines.append(f"| {label} | {_type_text(p)} | {_default_text(p)} | {prose(getattr(p, 'help', None) or '')} |")
    return lines + [""]


def cli_page() -> str:
    root = _click_command()
    flat = list(_commands(root, "studio"))
    lines = [GENERATED, "# Command line", "",
             f"`studio` has {len(flat)} commands, read from the typer app in `engine/cli.py`. "
             "`studio <command> --help` prints the same text in the terminal.", "",
             "Most commands take a project: a folder holding a `site.yaml`, given as a path or by name "
             "(a name is looked up in the projects folder, then in `examples/`).", "",
             "| Command | What it does |", "| --- | --- |"]
    for full, cmd in flat:
        lines.append(f"| [`{full}`](#{_anchor(full)}) | {prose(first_sentence(cmd.help or ''))} |")
    lines.append("")
    for full, cmd in flat:
        lines += [f"## `{full}` {{ #{_anchor(full)} }}", "", "```text", _usage(full, cmd), "```", ""]
        if cmd.help:
            lines += [block(cmd.help), ""]
        args = [p for p in cmd.params if _is_argument(p)]
        opts = [p for p in cmd.params if not _is_argument(p) and p.name != "help" and not getattr(p, "hidden", False)]
        if args:
            lines += _param_table("Argument", args)
        if opts:
            lines += _param_table("Option", opts)
    return "\n".join(lines)


# ---------------------------------------------------------------- the MCP reference

def _mcp_tools() -> list[Any]:
    from .mcp_server import mcp
    return asyncio.run(mcp.list_tools())


def mcp_page() -> str:
    tools = _mcp_tools()
    lines = [GENERATED, "# MCP tools", "",
             f"`python -m engine.mcp_server` starts an MCP server with {len(tools)} tools, so Claude Code, Claude Desktop "
             "or any MCP client can build sites with the engine. The repository's `.mcp.json` registers it for "
             "Claude Code. The tools are read from `engine/mcp_server.py`.", "",
             "Renders and recordings run in the background: the tool returns a job id, and `job_status` or "
             "`wait_for_job` reports on it. `snapshot` returns screenshot paths, so the client can look at its own work.", "",
             "| Tool | What it does |", "| --- | --- |"]
    for t in tools:
        lines.append(f"| [`{t.name}`](#{t.name.replace('_', '-')}) | {prose(first_sentence(t.description or ''))} |")
    lines.append("")
    no_ref = lambda n: f"`{n}`"  # noqa: E731
    for t in tools:
        lines += [f"## `{t.name}` {{ #{t.name.replace('_', '-')} }}", ""]
        if t.description:
            lines += [block(t.description), ""]
        sch = t.input_schema or {}
        props = sch.get("properties", {})
        if not props:
            lines += ["Takes no arguments.", ""]
            continue
        required = set(sch.get("required", []))
        lines += ["| Argument | Type | Default | Description |", "| --- | --- | --- | --- |"]
        for k, p in props.items():
            typ = type_md(p, no_ref)
            default = "**required**" if k in required else (code(p["default"]) if "default" in p else "")
            notes = [prose(p["description"])] if p.get("description") else []
            for allowed in enums_in(p):
                notes.append("Allowed values: " + ", ".join(code(v) for v in allowed) + ".")
            cons = constraints_in(p)
            if cons:
                notes.append("Constraints: " + "; ".join(cons) + ".")
            lines.append(f"| `{k}` | {typ} | {default} | {'<br>'.join(notes)} |")
        lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- entry points

def generate(out_dir: str | Path) -> list[Path]:
    """Write the three references under `out_dir` and return the files written."""
    out = Path(out_dir)
    written = [write(out / "spec" / name, text) for name, text in SpecDocs().render().items()]
    written.append(write(out / "cli.md", cli_page()))
    written.append(write(out / "mcp.md", mcp_page()))
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m engine.docsgen",
                                 description="Generate the site.yaml, CLI and MCP reference pages for the docs site.")
    ap.add_argument("out_dir", help="where to write them, normally docs/reference")
    args = ap.parse_args(argv)
    files = generate(args.out_dir)
    print(f"wrote {len(files)} reference pages under {args.out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
