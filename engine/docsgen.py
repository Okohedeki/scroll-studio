"""Reference pages generated from the engine itself, so they cannot drift from the code:

  python -m engine.docsgen docs/reference

writes `spec/` (every model and field of `site.yaml`, from the Pydantic spec), `cli.md` (every `studio` command and
option, from the typer app) and `mcp.md` (every MCP tool and its inputs, from the FastMCP server) into the folder.
The files are git-ignored; `mkdocs build` and CI generate them first (see docs/contributing/building-the-docs.md).

Importing the CLI and the MCP server is cheap (no torch, no GPU), so this runs in the docs CI job without the
`ml` extra. Nothing is started: the MCP tools are read from the registered functions, the CLI from its click command.
"""
