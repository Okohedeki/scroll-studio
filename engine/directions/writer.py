LETTERS = "abcdefghijkl"


def rng(seed, *parts) -> random.Random:
    return random.Random(f"{seed}/" + "/".join(str(p) for p in parts))


def _pick(r: random.Random, items, weights=None):
    items = list(items)
    if not items:
        return None
    return r.choices(items, weights=weights or [1] * len(items), k=1)[0]


# ---------------------------------------------------------------- constraints

class Rules:
    """The `directions:` block as predicates."""

    def __init__(self, brief: Brief):
        cfg: Directions = brief.cfg
        self.cfg = cfg
        self.keep = frozenset(cfg.keep)
        self.cur = brief.current
        self.warnings: list[str] = []
        known_styles = set(themes.styles()) | {"none"}
        for pool, label in ((cfg.styles.only, "styles.only"), (cfg.styles.avoid, "styles.avoid")):
            for s in pool:
                if s not in known_styles:
                    self.warnings.append(f"{label}: unknown style '{s}' (have: none, {', '.join(sorted(themes.styles()))})")
        known_fonts = set(typefaces.CLASS)
        for pool, label in ((cfg.fonts.only, "fonts.only"), (cfg.fonts.avoid, "fonts.avoid")):
            for f in pool:
                if f not in known_fonts:
                    self.warnings.append(f"{label}: '{f}' is not a font directions pairs (it can still avoid it); pairable: see `studio directions --list fonts`")
        self.only_fonts = {f.lower() for f in cfg.fonts.only}
        self.avoid_fonts = {f.lower() for f in cfg.fonts.avoid}
        self.only_pal = {p.lower() for p in cfg.palettes.only}
        self.avoid_pal = {p.lower() for p in cfg.palettes.avoid}
        self.brand = [c for c in cfg.palettes.brand if re.fullmatch(r"#?[0-9a-fA-F]{6}", c.strip())]
        if len(self.brand) != len(cfg.palettes.brand):
            self.warnings.append("palettes.brand: colours must be hex like #c2612a; the others are ignored")

    # --- styles
    def style_ok(self, style: str) -> bool:
        c = self.cfg.styles
        if "style" in self.keep:
            return style == (self.cur.get("style") or "none")
        if c.only and style not in c.only:
            return False
        return style not in c.avoid

    def styles_for(self, school) -> dict:
        return {s: w for s, w in school.styles.items() if self.style_ok(s) and (s == "none" or s in themes.styles())}

    # --- fonts
    def pairing_ok(self, p: vocab.Pairing) -> bool:
        fams = {p.display.lower(), p.body.lower(), p.mono.lower()}
        if fams & self.avoid_fonts:
            return False
        if self.only_fonts and not ({p.display.lower(), p.body.lower()} <= self.only_fonts):
            return False
        return True

    # --- palettes
    def palette_ok(self, p: vocab.Palette) -> bool:
        if p.name.lower() in self.avoid_pal:
            return False
        if self.only_pal and p.name.lower() not in self.only_pal:
            return False
        h, s, _ = measure.hsl(p.accent)
        for w in self.avoid_pal:
            if w in vocab.HUE_WORDS and s > 0.25:
                lo, hi = vocab.HUE_WORDS[w]
                if (lo <= h < hi) or (lo > hi and (h >= lo or h < hi)):
                    return False
        return True


# ---------------------------------------------------------------- composing one direction

def _contrast(a: str, b: str) -> float:
    return themes.contrast(themes._rgb(a), themes._rgb(b))


def _ink_on(color: str, options=("#ffffff", "#000000")) -> str:
    return max(options, key=lambda c: _contrast(color, c))


def _lighten(color: str, k: float) -> str:
    h, s, l = measure.hsl(color)
    r, g, b = colorsys.hls_to_rgb(h / 360, min(1, l + (1 - l) * k), s)
    return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))


def palette_dict(p: vocab.Palette) -> dict:
    d = {"name": p.name, "mode": p.mode, "bg": p.bg, "bg2": p.bg2, "ink": p.ink, "accent": p.accent, "accent2": p.accent2,
         "accent_ink": p.accent_ink or _ink_on(p.accent, (p.bg, p.ink, "#ffffff", "#000000"))}
    # the text on the accent button must read: take the better of the palette's own and the extremes
    if _contrast(d["accent"], d["accent_ink"]) < 4.5:
        d["accent_ink"] = _ink_on(d["accent"], (p.bg, p.ink, "#ffffff", "#000000"))
    return d


def with_brand(p: dict, brand: list[str]) -> dict:
    """The palette keeping its grounds and ink, with the brand colour(s) as accents."""
    a = "#" + brand[0].lstrip("#").lower()
    a2 = "#" + brand[1].lstrip("#").lower() if len(brand) > 1 else _lighten(a, 0.35)
    q = dict(p, name=f"{p['name']} · brand", accent=a, accent2=a2)
    q["accent_ink"] = _ink_on(a, (p["bg"], p["ink"], "#ffffff", "#000000"))
    return q


def current_palette(cur: dict) -> dict:
    c = cur.get("colors") or {}
    return {"name": "Today's palette", "mode": cur.get("mode", "dark"), "bg": c.get("bg", "#000000"),
            "bg2": c.get("bg2", c.get("bg", "#000000")), "ink": c.get("ink", "#ffffff"), "accent": c.get("accent", "#ff6b2c"),
            "accent2": c.get("accent2", c.get("accent", "#ffa66b")), "accent_ink": c.get("accent_ink", "#000000")}


def current_fonts(cur: dict) -> dict:
    f = cur.get("fonts") or {}
    return {"display": f.get("display", "Inter"), "body": f.get("body", "Inter"), "mono": f.get("mono", "IBM Plex Mono"),
            "weight": 500, "em": "accent", "italic_em": False, "labels": "caps", "note": "the site's own faces"}


def style_info(style: Optional[str]) -> tuple[str, str]:
    if not style:
        return "Editorial scroll", ("The engine's default page: sections follow one another with calm reveals, "
                                    "and the scenes in them do the performing.")
    st = themes.styles().get(style) or {}
    about = (st.get("about") or "").strip().replace("\n", " ")
    first = re.split(r"(?<=[.!?])\s+", about)[0] if about else ""
    return st.get("label", style), first


def compose(school: vocab.School, brief: Brief, rules: Rules, seed, used_styles=(), used_palettes=(), salt: str = "") -> Optional[Direction]:
    """One direction from one school: palette, pairing, style and look chosen by seed within the rules."""
    r = rng(seed, school.key, salt)
    # ---- style (an experience): by fit, and a style the set already uses is much less likely
    styles = rules.styles_for(school)
    if not styles:
        return None
    names = list(styles)
    ws = [styles[s] ** 2 * (0.12 if s in used_styles else 1.0) for s in names]
    style = _pick(r, names, ws)
    style = None if style == "none" else style
    # ---- palette
    if "colors" in rules.keep:
        pal = current_palette(brief.current)
    else:
        opts = [p for p in school.palettes if rules.palette_ok(p)]
        if not opts:
            return None
        pal = palette_dict(_pick(r, opts, [0.25 if p.name in used_palettes else 1.0 for p in opts]))
        if rules.brand:
            pal = with_brand(pal, rules.brand)
    # ---- type
    if "fonts" in rules.keep:
        fonts = current_fonts(brief.current)
    else:
        opts = [p for p in school.pairings if rules.pairing_ok(p)]
        if not opts:
            return None
        p = _pick(r, opts)
        italic = p.italic_em and p.display in typefaces.ITALIC
        fonts = {"display": p.display, "body": p.body, "mono": p.mono, "weight": p.weight, "em": p.em, "italic_em": italic,
                 "labels": p.labels, "note": p.note}
    fonts["display_class"] = typefaces.CLASS_LABEL.get(typefaces.CLASS.get(fonts["display"], ""), "")
    fonts["body_class"] = typefaces.CLASS_LABEL.get(typefaces.CLASS.get(fonts["body"], ""), "")
    # ---- imagery
    imagery, family, light_name = None, "", ""
    if "imagery" in rules.keep:
        imagery = brief.current.get("imagery")
        family = ""
    else:
        look = _pick(r, school.looks)
        light = look.light
        if look.lights:
            light_name = _pick(r, look.lights)
            light = vocab.LIGHTS[light_name]
        imagery = {"medium": look.medium, "light": light, "lens": look.lens, "mood": look.mood, "palette": look.palette}
        family = look.family
    label, about = style_info(style)
    concept = _pick(r, school.concepts).format(name=brief.name)
    return Direction(
        id="", school=school.key, name=school.name, kind=school.kind, concept=concept, palette=pal, fonts=fonts, style=style,
        style_label=label, style_about=about, imagery=imagery, imagery_family=family, light_name=light_name,
        motion=list(school.motion), voice=school.voice, pace=school.pace, radius=school.radius, board=school.board,
        unit=school.unit)


# ---------------------------------------------------------------- fit

def fit_of(school: vocab.School, brief: Brief, rules: Rules, seed) -> tuple[float, list[str]]:
    why = []
    dom_total = sum(brief.domains.values())
    if dom_total:
        dom = sum(w * school.domains.get(d, 0) for d, w in brief.domains.items()) / (3 * dom_total)
        best = max(brief.domains, key=lambda d: brief.domains[d] * school.domains.get(d, 0))
        if school.domains.get(best, 0):
            why.append(f"suits {best} ({school.domains[best]}/3)")
    else:
        dom = 0.35
    mood_total = sum(brief.moods.values())
    if mood_total:
        hit = [m for m, w in brief.moods.items() if m in school.moods]
        mood = sum(brief.moods[m] for m in hit) / mood_total
        if hit:
            why.append("mood: " + ", ".join(hit[:3]))
    else:
        mood = 0.35
    jitter = rng(seed, school.key, "fit").random()
    w_dom, w_mood = (0.55, 0.45) if mood_total else (0.8, 0.2)
    fit = 3 * (w_dom * dom + w_mood * mood) + 0.9 * jitter
    if school.objects_only and brief.places:      # a seamless backdrop cannot hold a river, a street or a room
        fit *= 0.5
        why.append("its backdrop cannot hold the page's places")
    return fit, why


def _school_distance(a: Direction, b: Direction, fixed) -> float:
    return measure.distance(a, b, fixed)


# ---------------------------------------------------------------- the set

class Result(dict):
    pass


def write(site: Site, raw: dict, cfg: Optional[Directions] = None, seed=None, count: Optional[int] = None) -> Result:
    """The directions for this site: {brief, directions: [Direction], diversity, warnings, seed, count}."""
    cfg = cfg or site.directions or Directions()
    seed = cfg.seed if seed is None else seed
    n = count or cfg.count
    brief = read(site, raw, cfg)
    rules = Rules(brief)
    fixed = rules.keep
    warnings = list(rules.warnings)

    scored = []
    for sc in vocab.SCHOOLS:
        fit, why = fit_of(sc, brief, rules, seed)
        d = compose(sc, brief, rules, seed)
        if d is None:
            continue
        d.fit, d.why = round(fit, 3), why
        scored.append((fit, sc, d))
    if not scored:
        raise ValueError("the constraints in `directions:` leave no direction to write (check styles, fonts and palettes)"
                         + ("; " + "; ".join(warnings) if warnings else ""))
    scored.sort(key=lambda x: -x[0])
    top = scored[0][0]
    floor = 0.6 * top                       # a pixel-art arcade for a cliff hotel is not a bold direction, it is a mistake
    pool = [x for x in scored if x[0] >= floor] or scored[:n]
    if len(pool) < n:
        pool = scored[:max(n, len(pool))]
    chosen: list[Direction] = []
    used_styles, used_pal = set(), set()

    def build(sc, fit, why):
        d = compose(sc, brief, rules, seed, used_styles, used_pal)
        d.fit, d.why = round(fit, 3), why
        return d

    remaining = list(pool)
    while remaining and len(chosen) < n:
        if not chosen:
            fit, sc, _d = remaining[0]
        else:
            def score(x):
                fit, sc, d = x
                cand = build(sc, fit, [])
                far = min(measure.distance(cand, c, fixed) for c in chosen)
                return fit + 1.5 * far + (0.5 if cand.kind not in {c.kind for c in chosen} else 0.0)
            fit, sc, _d = max(remaining, key=score)
        remaining = [x for x in remaining if x[1].key != sc.key]
        why = next(x[2].why for x in scored if x[1].key == sc.key)
        d = build(sc, fit, why)
        chosen.append(d)
        used_styles.add(d.style or "none")
        used_pal.add(d.palette["name"])
    # ---- repair: a pair that is too close is one idea twice. The weaker member (lower fit) is swapped for the school that
    # fits and differs most from the rest; a school once dropped is never brought back (no going round in circles)
    replaced, tabu = [], set()
    for _ in range(24):
        for i, d in enumerate(chosen):
            d.id = LETTERS[i]
        rep = measure.report(chosen, fixed)
        if rep["min"] >= measure.MIN_DISTANCE or len(chosen) < 2:
            break
        a, b = (next(d for d in chosen if d.id == k) for k in rep["closest"])
        weak = a if a.fit <= b.fit else b
        others = [d for d in chosen if d is not weak]
        have = {d.school for d in chosen} | tabu
        used_s, used_p = {o.style or "none" for o in others}, {o.palette["name"] for o in others}
        cands = []
        for fit, sc, _d in scored:
            if sc.key in have or fit < floor * 0.5:
                continue
            cand = compose(sc, brief, rules, seed, used_s, used_p)
            far = min(measure.distance(cand, o, fixed) for o in others)
            cand.fit, cand.why = round(fit, 3), next(x[2].why for x in scored if x[1].key == sc.key)
            cands.append((far >= measure.MIN_DISTANCE, fit + 1.5 * far, cand))
        if not cands:
            warnings.append(f"directions {a.id} ({a.name}) and {b.id} ({b.name}) are close (distance {rep['min']:.2f}); "
                            "the constraints leave no more different school to swap in")
            break
        new = max(cands, key=lambda c: (c[0], c[1]))[2]
        tabu.add(weak.school)
        replaced.append({"replaced": weak.name, "with": new.name, "distance": rep["min"], "was_close_to": (b if weak is a else a).name})
        chosen[chosen.index(weak)] = new
    for i, d in enumerate(chosen):
        d.id = LETTERS[i]
    if measure.report(chosen, fixed)["min"] < measure.MIN_DISTANCE and not any("close" in w for w in warnings):
        warnings.append(f"the closest pair is {measure.report(chosen, fixed)['min']:.2f} apart (below {measure.MIN_DISTANCE}): "
                        "the brief and constraints leave few schools to choose from")
    # ---- order by how far each is from today's site, and name the step
    cur = _current_as_direction(brief, rules)
    for d in chosen:
        d.distance_from_current = round(measure.distance(d, cur, fixed), 3)
    chosen.sort(key=lambda d: d.distance_from_current)
    third = max(1, len(chosen) // 3)
    for i, d in enumerate(chosen):
        d.id = LETTERS[i]
        d.stance = "closest to today" if i < third else ("a different site" if i >= len(chosen) - third and len(chosen) > 3 else "a step away")
    if len(chosen) < n:
        warnings.append(f"only {len(chosen)} of {n} directions: the brief and constraints leave no more schools that fit")
    res = Result(brief=brief.public(), directions=chosen, diversity=measure.report(chosen, fixed), replaced=replaced,
                 warnings=warnings, seed=seed, count=n, keep=sorted(fixed))
    return res


def _current_as_direction(brief: Brief, rules: Rules) -> Direction:
    cur = brief.current
    return Direction(id="today", school="", name="Today", kind="", concept="", palette=current_palette(cur),
                     fonts=dict(current_fonts(cur), display_class="", body_class=""), style=cur.get("style"),
                     imagery=cur.get("imagery"), imagery_family="")


def reroll(site: Site, raw: dict, current: list[Direction], which: str, cfg: Optional[Directions] = None, seed=None) -> Direction:
    """A different direction in place of `which`: the best school not yet used that fits and differs from the others."""
    cfg = cfg or site.directions or Directions()
    seed = cfg.seed if seed is None else seed
    brief = read(site, raw, cfg)
    rules = Rules(brief)
    others = [d for d in current if d.id != which]
    have = {d.school for d in current}
    salt = f"reroll-{which}-{len(have)}"
    cands = []
    for sc in vocab.SCHOOLS:
        if sc.key in have:
            continue
        fit, why = fit_of(sc, brief, rules, f"{seed}-{salt}")
        d = compose(sc, brief, rules, seed, {o.style or "none" for o in others}, {o.palette["name"] for o in others}, salt)
        if d is None:
            continue
        d.fit, d.why = round(fit, 3), why
        far = min((measure.distance(d, o, rules.keep) for o in others), default=1.0)
        cands.append((fit + 1.5 * far, d))
    if not cands:
        raise ValueError("no other school fits the constraints")
    d = max(cands, key=lambda x: x[0])[1]
    d.id = which
    d.distance_from_current = round(measure.distance(d, _current_as_direction(brief, rules), rules.keep), 3)
    old = next(x for x in current if x.id == which)
    d.stance = old.stance
    return d
