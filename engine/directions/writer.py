"""The writer: a brief and a seed in, a set of art directions out.

There is no local text model in this engine (ComfyUI's models/LLM holds Florence-2, a captioner, and Gemma is only
LTX's text encoder), so the ideas are not generated by one. They are *composed* from the curated vocabulary in vocab.py
(schools of design, palettes, type pairings, imagery treatments, photographers' lights, engine styles), chosen to fit the
brief and combined by a seed. The same brief and seed always give the same directions; another seed gives another
combination. Quality comes from the vocabulary being good and from `measure.py` insisting the set differs in kind.

  fit       how well a school suits the subject and mood words found in the site's copy and the brief
  spread    the set is built greedily: each next school fits well *and* is far from those already chosen
  repair    after the directions are composed, any pair closer than measure.MIN_DISTANCE is a weak pair: the weaker
            member (lower fit) is replaced by the next school that fits and differs, until the set holds up
"""
from __future__ import annotations

import colorsys
